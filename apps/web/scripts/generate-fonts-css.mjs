/**
 * Generates src/styles/base/fonts.css from the installed @fontsource packages.
 *
 * Why generate rather than import the packages' own CSS: Fontsource's stylesheets
 * reference files that Angular then hashes into media/, which makes
 * <link rel=preload> impossible. We copy the woff2 files under stable names via
 * asset globs and declare the faces ourselves — so the unicode-ranges must match
 * the packages exactly, which is what this script guarantees.
 *
 * It also COPIES the woff2 files into public/fonts/, because Angular refuses
 * asset paths outside its workspace root and node_modules is hoisted to the
 * monorepo root. public/fonts/ is therefore generated, gitignored, and rebuilt
 * by the prebuild/prestart hooks.
 *
 * Run: npm -w @lexi/web run fonts
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const nm = (p) => `${root}../../node_modules/${p}`;

/**
 * Public Sans covers the UI, but only latin/latin-ext — it has no Greek,
 * Cyrillic or Arabic, contrary to what was first assumed. Noto
 * fills those holes as a separate family in the stack; the browser does
 * per-codepoint fallback correctly, so layering everything under one family
 * name would only add a way for latin-ext overlaps to change which face renders
 * ASCII.
 *
 * CJK is deliberately absent: `ja` target *content* renders through system-ui
 * (every target OS ships a CJK face), and vendoring Noto Sans JP would cost
 * 4-8 MB for one locale.
 */
const FAMILIES = [
  {
    family: 'Public Sans',
    pkg: '@fontsource-variable/public-sans',
    prefix: 'public-sans',
    subsets: ['latin', 'latin-ext'],
    variable: true,
  },
  {
    family: 'IBM Plex Mono',
    pkg: '@fontsource/ibm-plex-mono',
    prefix: 'ibm-plex-mono',
    subsets: ['latin', 'latin-ext', 'cyrillic', 'cyrillic-ext'],
    weights: [400, 500],
  },
  {
    family: 'Noto Sans',
    pkg: '@fontsource-variable/noto-sans',
    prefix: 'noto-sans',
    subsets: ['greek', 'greek-ext', 'cyrillic', 'cyrillic-ext'],
    variable: true,
  },
  {
    family: 'Noto Sans Arabic',
    pkg: '@fontsource-variable/noto-sans-arabic',
    prefix: 'noto-sans-arabic',
    subsets: ['arabic'],
    variable: true,
  },
  {
    family: 'Noto Sans Hebrew',
    pkg: '@fontsource-variable/noto-sans-hebrew',
    prefix: 'noto-sans-hebrew',
    subsets: ['hebrew'],
    variable: true,
  },
  {
    family: 'Noto Sans Mono',
    pkg: '@fontsource-variable/noto-sans-mono',
    prefix: 'noto-sans-mono',
    // Plex Mono already carries Cyrillic; Noto Sans Mono is here only for Greek.
    subsets: ['greek', 'greek-ext'],
    variable: true,
  },
];

const face = ({ family, weight, file, range }) => `@font-face {
  font-family: '${family}';
  font-style: normal;
  font-weight: ${weight};
  font-display: swap;
  src: url('/fonts/${file}') format('woff2');
  unicode-range: ${range};
}`;

const fontsDir = `${root}public/fonts`;
rmSync(fontsDir, { recursive: true, force: true });
mkdirSync(fontsDir, { recursive: true });

const out = [
  '/*',
  ' * GENERATED by scripts/generate-fonts-css.mjs — do not edit by hand.',
  ' * Run `npm -w @lexi/web run fonts` after changing the font packages.',
  ' *',
  ' * NFR-1: every byte is served from this machine. Nothing is fetched from',
  ' * Google Fonts, at build time or at run time.',
  ' */',
  '',
];

const missing = [];
for (const fam of FAMILIES) {
  const ranges = JSON.parse(readFileSync(`${nm(fam.pkg)}/unicode.json`, 'utf8'));
  out.push(`/* ---- ${fam.family} (${fam.pkg}) ---- */`);
  for (const subset of fam.subsets) {
    const range = ranges[subset];
    if (!range) {
      missing.push(`${fam.pkg}: no unicode range for subset "${subset}"`);
      continue;
    }
    const weights = fam.variable ? ['100 900'] : fam.weights;
    for (const weight of weights) {
      const file = fam.variable
        ? `${fam.prefix}-${subset}-wght-normal.woff2`
        : `${fam.prefix}-${subset}-${weight}-normal.woff2`;
      if (!existsSync(`${nm(fam.pkg)}/files/${file}`)) {
        missing.push(`${fam.pkg}: missing file ${file}`);
        continue;
      }
      copyFileSync(`${nm(fam.pkg)}/files/${file}`, `${fontsDir}/${file}`);
      out.push(face({ family: fam.family, weight, file, range }));
    }
  }
  out.push('');
}

if (missing.length > 0) {
  console.error('Font generation failed:\n  ' + missing.join('\n  '));
  process.exit(1);
}

const target = `${root}src/styles/base/fonts.css`;
writeFileSync(target, out.join('\n'));
const faces = out.filter((l) => l.startsWith('@font-face')).length;
console.log(`Wrote ${target} and copied ${faces} woff2 files into public/fonts/`);
