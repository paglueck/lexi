/**
 * `<lx-icon name="trash" />` — decorative by construction: the SVG is always
 * `aria-hidden`, so the control that holds it must carry the accessible name
 * (an `aria-label`, or visible text beside the icon). Colour is `currentColor`,
 * which is what makes both themes and every button variant work with no CSS.
 */
@Component({
  selector: 'lx-icon',
  host: { class: 'lx-icon', '[attr.data-icon]': 'name()' },
  template: `
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      stroke-linecap="round"
      stroke-linejoin="round"
      [attr.width]="size()"
      [attr.height]="size()"
      [attr.stroke-width]="strokeWidth()"
      aria-hidden="true"
      focusable="false"
    >
      @for (d of paths(); track $index) {
        <path [attr.d]="d" />
      }
    </svg>
  `,
  styles: `
    :host {
      display: inline-flex;
      flex: none;
      line-height: 0;
    }
  `,
})
export class LxIcon {
  readonly name = input.required<IconName>();
  /** Rendered size in px; the handoff asks for 12–16. */
  readonly size = input(14);
  readonly strokeWidth = input(2);
  protected readonly paths = computed(() => ICONS[this.name()]);
}
